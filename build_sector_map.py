def classify(name, code):
    for keywords, sector in RULES:
        for kw in keywords:
            if kw in name or kw in code:
                return sector
    return '其他'

# 获取全量股票
print("获取股票列表...")
bs.login()
rs = bs.query_all_stock(day='2026-05-22')
total = 0
result = {}
while rs.next():
    row = rs.get_row_data()
    code = row[0].replace('sh.','').replace('sz.','')
    name = row[1]
    if len(code) == 6:
        result[code] = classify(name, code)
        total += 1
bs.logout()

